import 'package:flutter_test/flutter_test.dart';
import 'package:remotetester/pairing/pairing_uri.dart';

void main() {
  test('parses a valid pairing URI generated by the agent', () {
    final parsed = tryParsePairingUri(
      'remoteapptester://pair?host=100.81.17.106&port=50051&device_id=abc123'
      '&secret=topsecret&cert_fp=${'ab' * 32}&name=Telefon',
    );

    expect(parsed, isNotNull);
    expect(parsed!.address.host, '100.81.17.106');
    expect(parsed.address.port, 50051);
    expect(parsed.device.deviceId, 'abc123');
    expect(parsed.device.pairingSecret, 'topsecret');
    expect(parsed.certificate.fingerprintSha256Hex, 'ab' * 32);
    expect(parsed.displayName, 'Telefon');
  });

  test('rejects text that is not a remoteapptester:// URI', () {
    expect(tryParsePairingUri('not a uri at all'), isNull);
    expect(tryParsePairingUri('https://example.com/pair?host=x'), isNull);
    expect(tryParsePairingUri(''), isNull);
  });

  test('rejects a remoteapptester:// URI missing required fields', () {
    expect(tryParsePairingUri('remoteapptester://pair?host=100.81.17.106'), isNull);
    expect(
      tryParsePairingUri('remoteapptester://pair?host=h&port=notanumber&device_id=x&secret=y&cert_fp=z'),
      isNull,
    );
  });

  test('rejects a legacy URI missing cert_fp (must re-pair, not silently skip pinning)', () {
    expect(
      tryParsePairingUri('remoteapptester://pair?host=h&port=1&device_id=d&secret=s'),
      isNull,
    );
  });

  test('trims surrounding whitespace (e.g. from clipboard paste)', () {
    final parsed = tryParsePairingUri(
      '  remoteapptester://pair?host=h&port=1&device_id=d&secret=s&cert_fp=${'ab' * 32}  \n',
    );
    expect(parsed, isNotNull);
  });

  test('parses a URI actually generated by the host\'s buildPairingUri() (incl. real TLS fingerprint)', () {
    // Wygenerowane naprawdę przez `dart run tool/gen_test_qr_uri.dart` w
    // hosta (device_id/pairing_secret z prawdziwego DeviceRegistry,
    // cert_fp z prawdziwego TlsIdentity), nie ręcznie wymyślone — sprawdza,
    // że dwie niezależne implementacje formatu (host i telefon) faktycznie
    // się zgadzają, włącznie z polem cert_fp.
    const realUri = 'remoteapptester://pair?host=100.81.17.106&port=50051'
        '&device_id=LhL545WnYxoWMRU_O03nVw'
        '&secret=C6qGsitAF39llm8Lej4Yo8sfHGC0EXRPyjUbIXMpdro'
        '&cert_fp=1e79c1a323884e46ffecff6323e6806e1cf7fd5f4292abf2d160ea3f85c42942'
        '&name=QR+Cross-Check+Test+v2';

    final parsed = tryParsePairingUri(realUri);

    expect(parsed, isNotNull);
    expect(parsed!.address.host, '100.81.17.106');
    expect(parsed.address.port, 50051);
    expect(parsed.device.deviceId, 'LhL545WnYxoWMRU_O03nVw');
    expect(parsed.device.pairingSecret, 'C6qGsitAF39llm8Lej4Yo8sfHGC0EXRPyjUbIXMpdro');
    expect(
      parsed.certificate.fingerprintSha256Hex,
      '1e79c1a323884e46ffecff6323e6806e1cf7fd5f4292abf2d160ea3f85c42942',
    );
    expect(parsed.displayName, 'QR Cross-Check Test v2');
  });
}
